export function generateFallbackShows(movieId: number, dateStr?: string, theatreId?: number): Show[] {
  const chosenTheatres = theatreId
    ? FALLBACK_THEATRES.filter((t) => t.id === theatreId)
    : FALLBACK_THEATRES;
  const movie = FALLBACK_MOVIES.find((m) => m.id === movieId) || FALLBACK_MOVIES[0];
  const targetDate = dateStr || new Date().toISOString().split('T')[0];

  const timeSlots = ['10:00:00', '13:30:00', '16:45:00', '20:00:00', '22:45:00'];
  const shows: Show[] = [];

  let idCounter = movieId * 1000;
  for (const t of chosenTheatres) {
    for (const time of timeSlots) {
      idCounter++;
      shows.push({
        id: idCounter,
        movieId,
        theatreId: t.id,
        showDate: targetDate,
        showTime: time,
        movieTitle: movie.title,
        theatreName: t.name,
        format: t.formats.split(',')[0] || '3D',
        basePrice: 250,
      });
    }
  }
  return shows;
}

export function generateFallbackSeats(showId: number): Seat[] {
  const seatList: Seat[] = [];
  const rowLetters = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J'];
  // Semi-deterministic booked seats pattern based on showId
  const pseudoSeed = (showId % 7) + 2;

  for (const r of rowLetters) {
    for (let num = 1; num <= 12; num++) {
      const label = `${r}${num}`;
      const isStandard = r <= 'D';
      const isPremium = r >= 'E' && r <= 'H';
      const cat = isStandard ? 'standard' : isPremium ? 'premium' : 'recliner';
      const price = isStandard ? 150 : isPremium ? 240 : 550;

      // Realistic occupied seats distribution
      const isSold = (num * 3 + r.charCodeAt(0)) % pseudoSeed === 0;

      seatList.push({
        label,
        row: r,
        number: num,
        category: cat as any,
        price,
        status: isSold ? 'sold' : 'available',
      });
    }
  }
  return seatList;
}
